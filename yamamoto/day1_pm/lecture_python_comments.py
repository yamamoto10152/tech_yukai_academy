# =============================================================================
# 1. 1行コメント/コメントアウト（最もよく使う）
# =============================================================================
# 行の先頭に # を付けると、その右は「プログラムとして実行されない」説明文になる。
# 実行したいコードの前に # を付けると、その行はスキップされる＝コメントアウト。

answer = 40 + 2
# answer = 999  # ← こちらは「無効化」されているので、answer は 42 のまま
print("1. answer =", answer)


# =============================================================================
# 2. 行末コメント（短い補足）
# =============================================================================
pi_approx = 3.14  # 円周率の近似（本番では math.pi などを使うことが多い）
print("2. pi_approx =", pi_approx)


# =============================================================================
# 3. 複数行をまとめてコメントアウトする考え方
# =============================================================================
# Python には「/* ... */」のような公式のブロックコメント構文はない。
# その代わり、次のどちらかが現場でよく使われる。
#
# (A) 各行の先頭に # を付ける
#     → Cursor の「トグルコメント」（Ctrl + /）で一括で付け外しできる（別紙: lecture_editor_shortcuts.md）
#
# (B) トリプルクォートで囲む（次セクション参照）
#     → 注意点があるので「コメントのつもり」で乱用しないこと。


# =============================================================================
# 4. トリプルクォート """ ... """ は「コメント」ではなく「文字列」
# =============================================================================
# モジュール先頭のこのドキュメントのようなものは「docstring（ドックストリング）」と呼び、
# ツールや help() が読む説明文として使われる。
#
# 関数の直後に書くと、その関数の説明になる。


def add(a: int, b: int) -> int:
    """2つの整数を足して返す（これが関数の docstring）。"""
    return a + b


# コードの途中にだけ """ ... """ を置くと、それは「複数行の文字列リテラル」になる。
# 変数に代入しない場合、実行はされるが結果を使わないので「事実上スキップ」に見える。
# ただしインデントやクォートの閉じ忘れで SyntaxError になりやすいので、
# 「とりあえず動かない行を消す」用途には # 行コメントの方が安全なことが多い。

"""
このブロックは「複数行の文字列」だが、どこにも代入していない。
学習用に残しているだけ、という意味ではコメントに近い使われ方をすることもある。
本講義では「本当のコメントは # を使う」と覚えておくとよい。
"""

print("4. add(1, 2) =", add(1, 2))


# =============================================================================
# 5. 演習用ミニ課題（コメントアウトで挙動を変えてみる）
# =============================================================================
# 次の print は 2 行ある。どちらか一方だけが実行されるように、# を使って調整してみよう。
# ヒント: 実行したくない行の先頭に # を付ける。

print("5-A: こちらを表示したいときは、この行の # を外す")
# print("5-B: こちらを表示したいときは、上の行をコメントアウトしてこの行の # を外す")


if __name__ == "__main__":
    print("\n--- メインとして実行されました ---")
    print("docstring の確認: help(add) を試すと説明が見られます。")
