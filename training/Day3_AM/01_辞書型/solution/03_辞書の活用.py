"""
Day3: 辞書の活用（追加問題・任意）解答
売上・在庫データを辞書で管理する実務シナリオです
"""

# ========================================
# 問題1: 商品情報を辞書で管理しよう
# ========================================
product = {
    "商品名": "Oracleライセンス",
    "単価": 500000,
    "在庫数": 10
}
print(product)

# ========================================
# 問題2: 売上金額を計算しよう
# ========================================
total = product["単価"] * product["在庫数"]
print(f'{product["商品名"]}の売上合計: {total}円')
# → Oracleライセンスの売上合計: 5000000円

# ========================================
# 問題3: 在庫を更新しよう
# ========================================
product["在庫数"] = product["在庫数"] - 3
print(product["在庫数"])  # → 7

# ========================================
# 問題4: 新しい項目を追加しよう
# ========================================
product["担当者"] = "山田"
product["仕入れ値"] = 300000
print(product)

# ========================================
# 問題5: 全項目をレポート形式で表示しよう
# ========================================
for key, value in product.items():
    print(f"{key}: {value}")
# → 商品名: Oracleライセンス
# → 単価: 500000
# → 在庫数: 7
# → 担当者: 山田
# → 仕入れ値: 300000