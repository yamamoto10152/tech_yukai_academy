"""
Day3: 集合の活用（追加問題・任意）解答
取引先リストの比較シナリオです
"""

last_month = {"A社", "B社", "C社", "D社"}
this_month = {"B社", "C社", "D社", "E社", "F社"}

# ========================================
# 問題1: 今月も取引が続いている会社を調べよう
# ========================================
continued = last_month & this_month
print(continued)  # → {'B社', 'C社', 'D社'}

# ========================================
# 問題2: 今月から新しく取引が始まった会社を調べよう
# ========================================
new_clients = this_month - last_month
print(new_clients)  # → {'E社', 'F社'}

# ========================================
# 問題3: 先月から取引がなくなった会社を調べよう
# ========================================
lost_clients = last_month - this_month
print(lost_clients)  # → {'A社'}

# ========================================
# 問題4: 先月・今月合わせた全取引先を調べよう
# ========================================
all_clients = last_month | this_month
print(all_clients)  # → {'A社', 'B社', 'C社', 'D社', 'E社', 'F社'}

# ========================================
# 問題5: 特定の会社が継続取引しているか確認しよう
# ========================================
print("B社" in last_month and "B社" in this_month)  # → True