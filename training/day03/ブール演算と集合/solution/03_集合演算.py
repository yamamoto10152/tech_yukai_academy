A = {1, 2, 3, 4}
B = {3, 4, 5, 6}

print(A & B)   # 積集合 → {3, 4}
print(A | B)   # 和集合 → {1, 2, 3, 4, 5, 6}
print(A - B)   # 差集合 → {1, 2}


# リストから重複を除く

data = ["東京", "大阪", "東京", "名古屋", "大阪"]
