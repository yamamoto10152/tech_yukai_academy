# 基本の演算子（×÷の代わりに * と / を使う）

print(10 + 3)   # 足し算 → 13
print(10 - 3)   # 引き算 → 7
print(10 * 3)   # 掛け算 → 30
print(10 / 3)   # 割り算 → 3.3333333333333335
print(10 // 3)  # 切り捨て除算 → 3
print(10 % 3)   # 余り → 1


# 計算順序（* / が先、+ - が後。カッコで順序を変えられる）

print(2 + 3 * 4)      # → 14
print((2 + 3) * 4)    # → 20


# 切り捨てと余り

print(7 // 2)   # → 3
print(7 % 2)    # → 1
